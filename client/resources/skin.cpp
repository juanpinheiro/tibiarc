void Skin::Draw(Canvas &canvas, int id, int x, int y) const {
    canvas.Copy(Atlas, Area(id), x, y);
}

void Skin::Tile(Canvas &canvas,
                int id,
                const Rect &area,
                int offsetX,
                int offsetY) const {
    const Rect &source = Area(id);

    if (id == None || area.Empty() || source.Empty()) {
        return;
    }

    if (area.Width == source.Width && area.Height == source.Height) {
        canvas.Copy(Atlas, source, area.X, area.Y);
        return;
    }

    canvas.Tile(Atlas, source, area, offsetX, offsetY);
}

void Skin::DrawRegion(Canvas &canvas,
                      const Rect &source,
                      int x,
                      int y) const {
    canvas.Copy(Atlas, source, x, y);
}

